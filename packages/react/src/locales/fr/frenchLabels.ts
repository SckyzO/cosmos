// The French of every text the components write, the entry `@sckyzo/cosmos-react/locales/fr`:
// `<LabelsProvider labels={frenchLabels} locale="fr-FR">` shows them in French, and a dictionary of
// another language can start from a copy of it. It is typed as the whole `CosmosLabels`, so a key
// added to a component without its French fails the typecheck.
//
// How a French interface is written, so a translation can follow it:
// - A narrow no-break space (U+202F, written `\u202f`: it can't be told from a space on screen)
//   goes before `:`, `;`, `!`, `?` and `%`, inside « », and between a figure and its unit.
// - `…` is one character, and the apostrophe is the typographic ’.
// - A button or an action is named by an infinitive (Enregistrer), a sentence to the person by
//   `vous` (Saisissez, Appuyez sur).
// - French counts 0 and 1 as singular: a plural is `count <= 1 ? one : many`.
// - What a label says about a noun the app gives (`recordPager.noun`) is written for the noun of
//   the default, in the masculine: an app that passes another noun gives its own functions.

// The numbers the labels write themselves (a rating, a file size) are written as in France.
const LOCALE = 'fr-FR';

/** Text and nodes in one fragment: how the English builds a label that holds a node. */
const sentence = (...parts: ReactNode[]) => createElement(Fragment, null, ...parts);

const capitalize = (text: string) => `${text.charAt(0).toUpperCase()}${text.slice(1)}`;

/** A number as French writes it: `4,5`. */
const decimal = (value: number) => value.toLocaleString(LOCALE);

/**
 * A file size in octets, binary like the English KB and MB: `1,2 Mo`, one decimal, and two for the
 * gigabytes. The unit is picked after rounding.
 */
const octets = (bytes: number): string => {
  const fixed = (value: number, digits: number) =>
    value.toLocaleString(LOCALE, {
      minimumFractionDigits: digits,
      maximumFractionDigits: digits,
    });
  if (bytes < 1024) return `${bytes}\u202fo`;
  const ko = bytes / 1024;
  if (Number(ko.toFixed(1)) < 1024) return `${fixed(ko, 1)}\u202fKo`;
  const mo = ko / 1024;
  if (Number(mo.toFixed(1)) < 1024) return `${fixed(mo, 1)}\u202fMo`;
  return `${fixed(mo / 1024, 2)}\u202fGo`;
};

